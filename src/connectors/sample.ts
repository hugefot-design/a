export function sampleNotices(now = new Date()): NormalizedNotice[] {
  const day = 86_400_000;
  return SPECS.map((s) => {
    const deadline = s.deadlineDays === null ? null : new Date(now.getTime() + s.deadlineDays * day);
    if (deadline) deadline.setUTCHours(11, 0, 0, 0);
    const awards: NoticeAward[] = (s.awards ?? []).map((a) => ({
      lotTitle: a.lot ?? null,
      supplierName: a.supplier,
      supplierOrgNumber: null,
      value: a.value,
      currency: 'NOK',
      awardDate: new Date(now.getTime() - a.daysAgo * day).toISOString().slice(0, 10),
    }));
    return {
      source: 'sample',
      sourceNoticeId: s.id,
      sourceUrl: null,
      noticeType: s.lifecycle ?? 'competition',
      lifecycle: s.lifecycle ?? 'competition',
      procedureId: null,
      buyerReference: s.id,
      title: s.title,
      description: `${DISCLAIMER}\n\n${s.description}`,
      buyerName: s.buyer,
      buyerOrgNumber: null,
      buyerCity: s.place,
      countryCode: 'NO',
      nutsCodes: [s.nuts],
      placeText: s.place,
      cpvCodes: s.cpv,
      mainCpv: s.cpv[0] ?? null,
      contractNature: s.nature,
      procedureType: 'open',
      estimatedValue: s.value,
      currency: s.value !== null ? 'NOK' : awards.length ? 'NOK' : null,
      publishedAt: new Date(now.getTime() - s.publishedDaysAgo * day).toISOString(),
      deadlineAt: deadline ? deadline.toISOString() : null,
      deadlineTimeKnown: deadline !== null,
      documentsUrl: null,
      receivedTenders: s.received ?? null,
      awards,
      raw: { sample: true, id: s.id },
    } satisfies NormalizedNotice;
  });
}
